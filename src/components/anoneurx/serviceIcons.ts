export function getServiceIcon(issuer: string): ServiceIconData | undefined {
  if (!issuer) return undefined;
  const key = issuer.trim().toLowerCase();
  const slug = issuerToSlug[key] || key.replace(/[^a-z0-9]/g, "");

  if (customIcons[slug]) {
    return customIcons[slug];
  }

  const icon = iconMap[slug];
  if (icon) {
    return { path: icon.path, hex: icon.hex, title: icon.title };
  }

  return undefined;
}
